"""
    LEG_PERMUTATIONS

The six ordered factor orientations in `Q(a,b)`. Each tuple maps a leg of
the balanced seed to its original leg in `C(a,b)`. The first orientation
varies fastest in the combined tensor coordinates.
"""
const LEG_PERMUTATIONS = ((1, 2, 3), (3, 1, 2), (2, 3, 1), (2, 1, 3), (3, 2, 1), (1, 3, 2))

"""
    PolynomialDecomposition(dimensions, order)

Fourier rank decomposition of the polynomial multiplication tensor `C(a,b)`.
Store the three leg lengths and the root order as `BigInt` values. Each
evaluation point gives one rank-one term, whose coefficients are generated
individually by [`rank_coefficient`](@ref). Use [`polynomial_decomposition`](@ref)
to choose the dimensions and order.
"""
struct PolynomialDecomposition
    dimensions::NTuple{3,BigInt}
    order::BigInt
end

"""
    polynomial_dims(a::Integer, b::Integer)::NTuple{3,BigInt}

Return `(a, b, a + b - 1)`, the input and output leg dimensions of polynomial
multiplication. Both input lengths must be positive.
"""
function polynomial_dims(a::Integer, b::Integer)
    a > 0 && b > 0 || throw(ArgumentError("polynomial input lengths must be positive"))
    first, second = BigInt(a), BigInt(b)
    return (first, second, first + second - 1)
end

"""
    _sample_order(admissible_order, preferred, alternate)

Choose a positive `BigInt` Fourier order. Use `preferred` when the predicate
is `nothing`. Otherwise, try `preferred` and then `alternate` with the Boolean
predicate `admissible_order`. Throw `ArgumentError` when neither is admissible.
"""
function _sample_order(admissible_order, preferred, alternate)
    isnothing(admissible_order) && return preferred
    admissible_order(preferred) && return preferred
    admissible_order(alternate) && return alternate
    return throw(ArgumentError("neither root-of-unity order is invertible in the coefficient field"))
end

"""
    polynomial_decomposition(a, b; admissible_order=nothing)

Return a [`PolynomialDecomposition`](@ref) by evaluating and interpolating at
roots of unity, as in Theorem 3.1. The input lengths `a` and `b` are positive
integers. With a Boolean `admissible_order(order)` predicate, try the `BigInt`
orders `a + b - 1` and `a + b` in that order. Both exceed the product degree.
For field arithmetic the predicate should test that the order is invertible.
With `nothing`, use `a + b - 1`.
"""
function polynomial_decomposition(a, b; admissible_order=nothing)
    dimensions = polynomial_dims(a, b)
    minimum_order = dimensions[3]
    order = _sample_order(admissible_order, minimum_order, minimum_order + 1)
    return PolynomialDecomposition(dimensions, order)
end

"""
    size(decomposition::PolynomialDecomposition)::NTuple{3,BigInt}

Return the two input lengths and the product length of the underlying
polynomial multiplication tensor.
"""
Base.size(decomposition::PolynomialDecomposition) = decomposition.dimensions

rank_count(decomposition::PolynomialDecomposition) = decomposition.order

function rank_coefficient(
    decomposition::PolynomialDecomposition, term::Integer, leg::Integer, coordinate::Integer
)
    check_rank_coordinate(decomposition, term, leg, coordinate)
    order = rank_count(decomposition)
    exponent = (BigInt(term) - 1) * (BigInt(coordinate) - 1)
    # The inverse Vandermonde is the conjugate transform divided by its side.
    return if leg == 3
        root_of_unity(order, -exponent) / order
    else
        root_of_unity(order, exponent)
    end
end

"""
    SeedDecomposition(polynomial, copies, dimensions, terms)

Rank decomposition of `Q(a,b)` raised to `copies`. Store its base
[`PolynomialDecomposition`](@ref), its `BigInt` copy count, three leg lengths,
and rank-term count. Coefficients are generated by mixed-radix indexing into
the six orientations of each copy. Use [`seed_decomposition`](@ref) to
compute the metadata from `a`, `b`, and the copy count.
"""
struct SeedDecomposition
    polynomial::PolynomialDecomposition
    copies::BigInt
    dimensions::NTuple{3,BigInt}
    terms::BigInt
end

"""
    seed_dims(a, b)::NTuple{3,BigInt}

Return the three equal leg dimensions of `Q(a,b)` for positive integer
input lengths. Each dimension is `(a * b * (a + b - 1))^2`.
"""
function seed_dims(a, b)
    dimension = prod(polynomial_dims(a, b))^2
    return (dimension, dimension, dimension)
end

"""
    seed_decomposition(a, b, m::Integer=1; admissible_order=nothing)

Return a [`SeedDecomposition`](@ref) of `Q(a,b)⊗m` for positive integer
lengths `a` and `b` and a nonnegative copy count `m`. The first tensor factor
varies fastest. At `m = 0`, the result has one rank term and one coordinate on
each leg. Use `admissible_order` as in [`polynomial_decomposition`](@ref).
"""
function seed_decomposition(a, b, m::Integer=1; admissible_order=nothing)
    m >= 0 || throw(ArgumentError("the number of seed copies must be nonnegative"))
    polynomial = polynomial_decomposition(a, b; admissible_order)
    copies = BigInt(m)
    dimensions = map(dimension -> dimension^copies, seed_dims(a, b))
    return SeedDecomposition(
        polynomial, copies, dimensions, rank_count(polynomial)^(6copies)
    )
end

"""
    size(decomposition::SeedDecomposition)::NTuple{3,BigInt}

Return the leg dimensions of the balanced seed tensor power. Each is the
corresponding [`seed_dims`](@ref) entry raised to the copy count.
"""
Base.size(decomposition::SeedDecomposition) = decomposition.dimensions

"""
    size(decomposition::Union{PolynomialDecomposition,SeedDecomposition}, leg::Integer)::BigInt

Return the length of the leg indexed by `leg` in `1:3`. An invalid leg index
throws `BoundsError`.
"""
function Base.size(
    decomposition::Union{PolynomialDecomposition,SeedDecomposition}, leg::Integer
)
    return size(decomposition)[leg]
end

rank_count(decomposition::SeedDecomposition) = decomposition.terms

"""
    rank_count(decomposition)::BigInt

Return the number of terms in the chosen rank decomposition. For
[`PolynomialDecomposition`](@ref) this is the Fourier order. For
[`SeedDecomposition`](@ref) it is that order raised to six times the copy
count. These counts are upper bounds on tensor rank.
"""
rank_count

"""
    check_rank_coordinate(decomposition, term, leg, coordinate)

Check integer rank-term, leg, and coordinate indices, all one-based. The
decomposition must support [`rank_count`](@ref) and a three-leg `size` tuple.
Throw `BoundsError` on the first invalid index. Return `nothing` on success.
"""
function check_rank_coordinate(decomposition, term, leg, coordinate)
    1 <= leg <= 3 || throw(BoundsError(1:3, leg))
    1 <= term <= rank_count(decomposition) || throw(BoundsError(decomposition, term))
    1 <= coordinate <= size(decomposition)[leg] ||
        throw(BoundsError(decomposition, coordinate))
    return nothing
end

function rank_coefficient(
    decomposition::SeedDecomposition, term::Integer, leg::Integer, coordinate::Integer
)
    check_rank_coordinate(decomposition, term, leg, coordinate)
    polynomial = decomposition.polynomial
    order = rank_count(polynomial)
    exponent = big(0)
    term_index, coordinate_index = BigInt(term) - 1, BigInt(coordinate) - 1
    for _ in 1:decomposition.copies, permutation in LEG_PERMUTATIONS
        original_leg = permutation[leg]
        term_index, term_digit = divrem(term_index, order)
        coordinate_index, coordinate_digit = divrem(
            coordinate_index, size(polynomial)[original_leg]
        )
        local_exponent = term_digit * coordinate_digit
        exponent += original_leg == 3 ? -local_exponent : local_exponent
    end
    # Each leg includes the polynomial output twice per seed copy.
    return root_of_unity(order, exponent) / order^(2decomposition.copies)
end

"""
    rank_coefficient(decomposition, term::Integer, leg::Integer, coordinate::Integer)

Return one entry of a rank-one factor as a `Rational{BigInt}` or
[`PhaseSum`](@ref). All indices are one-based and are checked against the
decomposition's dimensions and [`rank_count`](@ref).

For [`PolynomialDecomposition`](@ref), the input legs use Fourier evaluation
and the output leg uses the inverse transform. For [`SeedDecomposition`](@ref),
decode the indices across copies and orientations in first-factor-fastest
order and multiply the corresponding Fourier coefficients.
"""
rank_coefficient

"""
    baseline_source_coordinate(dimensions, scalar_leg, leg, matrix_size, digit_base, coordinate)::BigInt

Map a one-based matrix coordinate of the baseline restriction to its source
coordinate in leg `leg` of `Q(a,b)`. Here `dimensions` contains the three
leg lengths of `C(a,b)`, `scalar_leg` is the shorter input leg, `digit_base`
is the longer input length, and `matrix_size` is `digit_base^2`.

In each orientation, the shorter input is fixed to its constant term. The
remaining dot product shares one digit of the row, inner, or column index
depending on the position of that scalar leg. Matrix coordinates use Julia
column-major order.
"""
function baseline_source_coordinate(
    dimensions, scalar_leg, leg, matrix_size, digit_base, coordinate
)
    column, row = divrem(BigInt(coordinate) - 1, matrix_size)
    unused = big(0)
    axis_digits = if leg == 1
        (unused, row, column)
    elseif leg == 2
        (column, unused, row)
    else
        (column, row, unused)
    end
    source = big(0)
    stride = big(1)
    for permutation in LEG_PERMUTATIONS
        original_leg = permutation[leg]
        if original_leg != scalar_leg
            # Each orientation contains the original scalar leg once.
            missing_leg = findfirst(==(scalar_leg), permutation)
            remaining, digit = divrem(axis_digits[missing_leg], digit_base)
            axis_digits = Base.setindex(axis_digits, remaining, missing_leg)
            source += stride * digit
        end
        stride *= dimensions[original_leg]
    end
    return source + 1
end

"""
    seed_matrix_selection(a, b, target_dimensions, matrix_coordinate)

Build a [`TensorRestriction`](@ref) using the baseline matrix selection for
positive integer seed lengths `a` and `b`. The `target_dimensions` tuple
specifies three `BigInt` leg lengths. For each leg, `matrix_coordinate(row)`
maps a one-based `BigInt` target row to a one-based coordinate of the baseline
matrix tensor.
"""
function seed_matrix_selection(a, b, target_dimensions, matrix_coordinate)
    dimensions = polynomial_dims(a, b)
    source_dimensions = seed_dims(a, b)
    scalar_leg = a <= b ? 1 : 2
    digit_base = BigInt(max(a, b))
    matrix_size = digit_base^2
    legs = ntuple(3) do leg
        # A BigInt target row maps to one BigInt source column for this leg.
        source_column = function (row)
            return baseline_source_coordinate(
                dimensions,
                scalar_leg,
                leg,
                matrix_size,
                digit_base,
                matrix_coordinate(row),
            )
        end
        return selection_map(source_dimensions[leg], target_dimensions[leg], source_column)
    end
    return TensorRestriction(legs...)
end

"""
    seed_baseline(a::Integer, b::Integer)

Restrict `Q(a,b)` to the matrix multiplication tensor whose side is
`max(a,b)^2`, using Lemmas 3.4 and 3.8. The input lengths must be positive.
"""
function seed_baseline(a::Integer, b::Integer)
    return seed_matrix_selection(a, b, mm_dims(BigInt(max(a, b))^2), identity)
end

"""
    seed_unit(a::Integer, b::Integer)

Restrict `Q(a,b)` to the two-dimensional unit tensor by selecting two
diagonal coordinates in the baseline matrix tensor. The input lengths must
be positive, and at least one must exceed one.
"""
function seed_unit(a::Integer, b::Integer)
    matrix_size = BigInt(max(a, b))^2
    matrix_size >= 2 || throw(ArgumentError("a seed of size (1,1) cannot restrict to I₂"))
    return seed_matrix_selection(
        a, b, unit_dims(2), row -> 1 + (row - 1) * (matrix_size + 1)
    )
end
